def main() -> int:
    out = sys.argv[1] if len(sys.argv) > 1 else "/tests/ground_truth_poc"
    data = binascii.unhexlify("".join(POC_HEX.split()))
    digest = hashlib.sha256(data).hexdigest()
    expect = "e26a3699e12eef0dac7f11d193f64d7aebec89f6139e106f228a6fb0a4a28809"
    if digest != expect:
        sys.stderr.write(f"poc sha256 mismatch: {digest} != {expect}\n")
        return 1
    with open(out, "wb") as fh:
        fh.write(data)
    return 0


