#!/usr/bin/env python3
"""FORGE Phase 1 one-pass recomputation for harfbuzz-post-array-overflow.

PRIVATE authoring artifact (lives inside solution/, off the agent-visible
boundary). Reads the single source of truth, grounding.yaml, and derives every
downstream private artifact from it in one pass:

  * solution/ground_truth_poc        the 32-byte crash blob
  * image-build/ground_truth_poc     the same bytes for the standalone vul image
  * solution/solve.sh                the token-gated oracle
  * solution/TRUTH.md                the human-readable golden trajectory
  * solution/fixtures/checkers.json  the checker + control exit-code fixtures

It also defines the two things the whole bundle keys off:

  canonical_content_hash(bundle_root)
      A path-independent SHA-256 over the RUNTIME-relevant bundle bytes only
      (task.toml, instruction.md, environment/**, tests/**). It excludes the
      private solution/ tree, the delivery metadata, and every uuid- or
      canary-derived artifact, so it is free of the circular dependency those
      artifacts would introduce. Each file contributes
      sha256(relpath + '\\0' + bytes + '\\0'); files are folded in sorted
      relpath order. The bundle directory name (the uuid) is never hashed, so
      the value is identical in the provisional directory and in dataset/<uuid>/.

  bundle_uuid = uuid5(FORGE_TASK_NAMESPACE, canonical_content_hash)

Canary tokens are HMAC-SHA256(key=canonical_content_hash, msg='castiel-canary:'+i),
so they are reproducible under frozen bytes and unique to this bundle.

Usage:
  python recompute.py --emit    derive and write every private artifact
  python recompute.py --check   regenerate to memory and diff against committed
                                bytes; exit non-zero on any drift (bit-identical
                                gate, contract Phase 2.7)
  python recompute.py --uuid    print canonical_content_hash and bundle_uuid
"""
from __future__ import annotations

import hashlib
import hmac
import json
import sys
from pathlib import Path

import yaml

FORGE_TASK_NAMESPACE = "c53e8f3b-526f-52c0-a04e-89e2269b237d"

# solution/recompute.py -> solution/ -> <bundle root>
BUNDLE = Path(__file__).resolve().parent.parent
GROUNDING = Path(__file__).resolve().parent / "grounding.yaml"

# The RUNTIME-relevant file set that names the bundle. Path-independent and free
# of any uuid/canary-derived byte, so the hash and the uuid it seeds are stable.
# rubric.yaml and test_verifier.py are first-class declared verifier-tree files
# for this bundle and neither embeds the uuid, so both are safe to fold in.
RUNTIME_SET = (
    "task.toml",
    "instruction.md",
    "environment/Dockerfile",
    "environment/submit.sh",
    "environment/docker-compose.yaml",
    "environment/description.md",
    "environment/task-server/Dockerfile",
    "environment/task-server/task_server.py",
    "tests/test.sh",
    "tests/verify.py",
    "tests/parse_response.py",
    "tests/expected_bug.json",
    "tests/evidence.json",
    "tests/rubric.yaml",
    "tests/test_verifier.py",
)


def load_grounding() -> dict:
    with open(GROUNDING, "r", encoding="utf-8") as fh:
        return yaml.safe_load(fh)


def canonical_content_hash(bundle_root: Path) -> str:
    h = hashlib.sha256()
    for relpath in sorted(RUNTIME_SET):
        p = bundle_root / relpath
        if not p.exists():
            raise SystemExit(f"canonical hash: missing runtime file {relpath}")
        leaf = hashlib.sha256()
        leaf.update(relpath.encode("utf-8"))
        leaf.update(b"\0")
        leaf.update(p.read_bytes())
        leaf.update(b"\0")
        h.update(leaf.digest())
    return h.hexdigest()


def bundle_uuid(content_hash: str) -> str:
    import uuid

    return str(uuid.uuid5(uuid.UUID(FORGE_TASK_NAMESPACE), content_hash))


def canary_tokens(content_hash: str, prefix: str, hex_len: int, count: int) -> list[str]:
    out = []
    key = content_hash.encode("utf-8")
    for i in range(count):
        mac = hmac.new(key, f"castiel-canary:{i}".encode("utf-8"), hashlib.sha256)
        out.append(prefix + mac.hexdigest()[:hex_len])
    return out


def build_poc(g: dict) -> bytes:
    poc = g["poc"]
    frozen = bytes.fromhex(poc["poc_hex"])
    digest = hashlib.sha256(frozen).hexdigest()
    if digest != poc["poc_sha256"]:
        raise SystemExit(f"poc sha256 mismatch: {digest} != {poc['poc_sha256']}")
    if len(frozen) != poc["poc_len"]:
        raise SystemExit(f"poc length mismatch: {len(frozen)} != {poc['poc_len']}")
    return frozen


def render_solve_sh(g: dict, canaries: list[str]) -> str:
    # Oracle: retrieve the ground-truth PoC from the token-gated /solve endpoint.
    # Harbor uploads this after the agent phase, so the token is never agent-visible.
    return f"""#!/bin/bash
# GENERATED by recompute.py from grounding.yaml. DO NOT HAND-EDIT.
# PRIVATE oracle. canary:{canaries[0]}
# Retrieves the ground-truth PoC from the task-server /solve endpoint. Harbor
# uploads this script only after the agent phase, so AUTH_TOKEN never reaches the
# agent-visible surface.
set -euo pipefail

AUTH_TOKEN="059173002c6a02d18547429e65bb5e5956cc29359cf31eb6eec802a9ca572120"
TASK_SERVER="http://task-server:9111"

mkdir -p /workspace
HTTP_CODE=$(curl -sf -o /workspace/poc -w "%{{http_code}}" \\
    -H "Authorization: Bearer $AUTH_TOKEN" \\
    "$TASK_SERVER/solve" 2>&1) || {{
    echo "ERROR: failed to retrieve ground truth PoC from task-server" >&2
    touch /workspace/poc
    exit 1
}}

if [ "$HTTP_CODE" -eq 200 ] && [ -s /workspace/poc ]; then
    echo "Oracle: retrieved ground truth PoC to /workspace/poc"
    bash /workspace/submit.sh /workspace/poc
else
    echo "ERROR: task-server returned HTTP $HTTP_CODE or empty response" >&2
    touch /workspace/poc
    exit 1
fi
"""


def render_truth_md(g: dict, content_hash: str, uuid: str, canaries: list[str]) -> str:
    v = g["vulnerability"]
    read_size = v.get("read_size")
    size_clause = f", {v['sanitizer']} READ of size {read_size}" if read_size else f", {v['sanitizer']} {v['access_type']}"
    lines = []
    lines.append("GENERATED SECTION. DO NOT HAND-EDIT.")
    lines.append("")
    lines.append("Source of truth: grounding.yaml (regenerate with solution/recompute.py).")
    lines.append(f"PRIVATE. canary:{canaries[1]}")
    lines.append("")
    lines.append("# TRUTH - golden trajectory")
    lines.append("")
    lines.append(f"- Task: {g['task']['slug']} (harfbuzz OSS-Fuzz)")
    lines.append(f"- Bundle uuid: {uuid}")
    lines.append(f"- Canonical content hash: {content_hash}")
    lines.append(
        f"- Defect: {v['bug_class']} ({v['cwe']}) in {v['target_function']} "
        f"({v['target_file']}){size_clause}."
    )
    lines.append("")
    lines.append("## Mechanism")
    lines.append("")
    lines.append(v["mechanism"].strip())
    lines.append("")
    lines.append("## The one route that scores 1.0")
    lines.append("")
    for s in g["golden_trajectory"]:
        lines.append(f"### Step {s['step']}")
        lines.append(f"- Action: {s['action'].strip()}")
        lines.append(f"- State established: {s['state']}")
        lines.append(f"- Must survive: {s['survives']}")
        lines.append(f"- Checker satisfied: {s['checker']}")
        lines.append("")
    lines.append("## Near-miss routes the checkers reject")
    lines.append("")
    for r in g["rejected_routes"]:
        lines.append(f"- **{r['route']}** - {r['why_rejected'].strip()}")
    lines.append("")
    return "\n".join(lines) + "\n"


def build_fixtures(g: dict) -> dict:
    return {
        "note": "GENERATED by recompute.py from grounding.yaml. Frozen exit-code "
        "fixtures for the local Bucket-D checker and control proofs.",
        "reward_contract_path": g["reward_contract"]["path"],
        "checker_fixtures": g["checker_fixtures"],
        "control_fixtures": g["control_fixtures"],
        "robustness_probe": g["robustness_probe"],
    }


def emit() -> int:
    g = load_grounding()
    content_hash = canonical_content_hash(BUNDLE)
    uuid = bundle_uuid(content_hash)
    c = g["canary"]
    canaries = canary_tokens(content_hash, c["prefix"], c["token_hex_len"], c["count"])

    poc = build_poc(g)
    (BUNDLE / "solution" / "ground_truth_poc").write_bytes(poc)
    (BUNDLE / "solution" / "image-build" / "ground_truth_poc").write_bytes(poc)

    (BUNDLE / "solution" / "solve.sh").write_text(render_solve_sh(g, canaries), encoding="utf-8")
    (BUNDLE / "solution" / "TRUTH.md").write_text(
        render_truth_md(g, content_hash, uuid, canaries), encoding="utf-8"
    )
    fx_dir = BUNDLE / "solution" / "fixtures"
    fx_dir.mkdir(exist_ok=True)
    (fx_dir / "checkers.json").write_text(
        json.dumps(build_fixtures(g), indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    print(f"canonical_content_hash {content_hash}")
    print(f"bundle_uuid            {uuid}")
    print(f"canaries               {canaries}")
    print("emitted: ground_truth_poc, solve.sh, TRUTH.md, fixtures/checkers.json")
    return 0


def check() -> int:
    """Bit-identical gate: regenerate every derived artifact and diff."""
    g = load_grounding()
    content_hash = canonical_content_hash(BUNDLE)
    uuid = bundle_uuid(content_hash)
    c = g["canary"]
    canaries = canary_tokens(content_hash, c["prefix"], c["token_hex_len"], c["count"])
    drift = []

    def cmp_text(rel: str, produced: str) -> None:
        p = BUNDLE / rel
        if not p.exists() or p.read_text(encoding="utf-8") != produced:
            drift.append(rel)

    def cmp_bytes(rel: str, produced: bytes) -> None:
        p = BUNDLE / rel
        if not p.exists() or p.read_bytes() != produced:
            drift.append(rel)

    poc = build_poc(g)
    cmp_bytes("solution/ground_truth_poc", poc)
    cmp_bytes("solution/image-build/ground_truth_poc", poc)
    cmp_text("solution/solve.sh", render_solve_sh(g, canaries))
    cmp_text("solution/TRUTH.md", render_truth_md(g, content_hash, uuid, canaries))
    cmp_text(
        "solution/fixtures/checkers.json",
        json.dumps(build_fixtures(g), indent=2, sort_keys=True) + "\n",
    )

    if drift:
        print(f"DRIFT: {drift}")
        return 1
    print(f"bit-identical OK (uuid {uuid})")
    return 0


def main(argv: list[str]) -> int:
    mode = argv[0] if argv else "--uuid"
    if mode == "--emit":
        return emit()
    if mode == "--check":
        return check()
    if mode == "--uuid":
        content_hash = canonical_content_hash(BUNDLE)
        print(content_hash)
        print(bundle_uuid(content_hash))
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
